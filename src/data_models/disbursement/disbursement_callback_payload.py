"""Asynchronous payment rail clearing status callback schema."""

from pydantic import Field, model_validator

from src.data_models.common import (
    DisbursementFailureCode,
    DisbursementStatus,
    DisbursementTxnId,
    StrictBaseModel,
    UtcTimestamp,
)


class DisbursementCallbackPayload(StrictBaseModel):
    """Data model representing an asynchronous payment rail clearing callback.

    Captures financial clearing status and banking references returned by national payment
    gateways.

    Invariants:
    - `bank_reference_id` is mandatory across all statuses for audit reconciliation.
    - `FAILED` and `RETURNED` statuses strictly require `failure_reason_code`.
    - `SUCCESS` status strictly forbids `failure_reason_code`.

    See: decisions/step2.0_canonical_domain_schemas.md (Section 4.5)
    See: decisions/step2.2_governance_flows_and_state_transitions.md (Section 4.4)
    """

    disbursement_txn_id: DisbursementTxnId
    bank_reference_id: str = Field(
        ...,
        min_length=5,
        max_length=64,
        description=(
            "External banking UTR or clearing reference generated by NPCI/PFMS bank rail. "
            "Required for all statuses for audit reconciliation."
        ),
    )
    disbursement_status: DisbursementStatus
    cleared_at: UtcTimestamp = Field(
        ...,
        description="UTC timestamp when sovereign payment rail cleared or errored transaction",
    )
    failure_reason_code: DisbursementFailureCode | None = Field(
        default=None,
        description="Populated if status is FAILED or RETURNED",
    )

    @model_validator(mode="after")
    def validate_terminal_failure_reason(self) -> "DisbursementCallbackPayload":
        """Enforces mandatory failure justification when financial clearing fails or returns.

        Why require failure_reason_code?
        When APBS or PFMS bank clearing fails (e.g., INVALID_IFSC or ACCOUNT_BLOCKED), the
        system
        must capture explicit error codes to trigger citizen re-notification and automated
        conversational correction loops without human caseworker intervention.
        """
        terminal_failures = {
            DisbursementStatus.FAILED,
            DisbursementStatus.RETURNED,
        }
        if self.disbursement_status in terminal_failures and (
            not self.failure_reason_code or not self.failure_reason_code.strip()
        ):
            raise ValueError(
                "failure_reason_code is required for disbursement status "
                f"{self.disbursement_status}"
            )
        return self

    @model_validator(mode="after")
    def validate_success_clearing_fields(self) -> "DisbursementCallbackPayload":
        """Enforces that failure codes are excluded upon successful clearing.

        Why forbid failure_reason_code on SUCCESS?
        Successful transactions must not carry failure telemetry. The bank_reference_id is
        required for all statuses (maintained at schema level) to ensure audit trail
        continuity
        across SUCCESS, FAILED, and RETURNED outcomes.
        """
        if (
            self.disbursement_status == DisbursementStatus.SUCCESS
            and self.failure_reason_code is not None
        ):
            raise ValueError("failure_reason_code must be None when disbursement status is SUCCESS")
        return self
