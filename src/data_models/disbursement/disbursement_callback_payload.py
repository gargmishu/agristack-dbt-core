"""Asynchronous payment rail clearing status callback schema."""

from pydantic import Field, model_validator

from src.data_models.common import (
    DisbursementFailureCode,
    DisbursementStatus,
    DisbursementTxnId,
    StrictBaseModel,
    UtcTimestamp,
)


class DisbursementCallbackPayload(StrictBaseModel):
    """Asynchronous payment status callback from PFMS / NPCI / OpenSPP payment rails.

    See: decisions/step2.0_canonical_domain_schemas.md (Section 4.5)
    """

    disbursement_txn_id: DisbursementTxnId = Field(
        ...,
        description="Internal idempotency order ID matching Layer 4 governance approval key",
    )
    bank_reference_id: str | None = Field(
        None,
        min_length=5,
        max_length=64,
        description="External banking UTR or clearing reference generated by NPCI/PFMS bank rail",
    )
    disbursement_status: DisbursementStatus = Field(
        ..., description="Updated financial clearing state: SUCCESS, FAILED, RETURNED"
    )
    cleared_at: UtcTimestamp = Field(
        ...,
        description="UTC timestamp when sovereign payment rail cleared or errored transaction",
    )
    failure_reason_code: DisbursementFailureCode | None = Field(
        None,
        description="Populated if status is FAILED or RETURNED",
    )

    @model_validator(mode="after")
    def validate_terminal_failure_reason(self) -> "DisbursementCallbackPayload":
        """Enforces mandatory failure justification when financial clearing fails or returns.

        Why require failure_reason_code?
        When APBS or PFMS bank clearing fails (e.g., INVALID_IFSC or ACCOUNT_BLOCKED), the system
        must capture explicit error codes to trigger citizen re-notification and automated
        conversational correction loops without human caseworker intervention.
        """
        terminal_failures = {
            DisbursementStatus.FAILED,
            DisbursementStatus.RETURNED,
        }
        if self.disbursement_status in terminal_failures and (
            not self.failure_reason_code or not self.failure_reason_code.strip()
        ):
            raise ValueError(
                "failure_reason_code is required for disbursement status "
                f"{self.disbursement_status}"
            )
        return self

    @model_validator(mode="after")
    def validate_success_clearing_fields(self) -> "DisbursementCallbackPayload":
        """Enforces external banking UTR and exclusion of failure codes upon successful clearing.

        Why require bank_reference_id (UTR) and forbid failure_reason_code on SUCCESS?
        While `disbursement_txn_id` serves as AgriStack's internal instruction idempotency key,
        an approved payout must carry the external bank-generated UTR (`bank_reference_id`)
        for audit reconciliation and citizen receipts. Simultaneously, it must never carry failure
        telemetry.
        """
        if self.disbursement_status == DisbursementStatus.SUCCESS:
            if not self.bank_reference_id or not self.bank_reference_id.strip():
                raise ValueError(
                    "bank_reference_id (UTR) is required when disbursement status is SUCCESS"
                )
            if self.failure_reason_code is not None:
                raise ValueError(
                    "failure_reason_code must be None when disbursement status is SUCCESS"
                )
        return self
